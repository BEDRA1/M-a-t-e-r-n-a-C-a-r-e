const defaultResponse =
  "شكراً لسؤالكِ. للحصول على إجابة دقيقة ومخصصة لوضعكِ، نوصيكِ باستشارة إحدى أخصائياتنا مباشرة.";

export function getDoulaResponse(userMessage: string): string {
  const message = userMessage.toLowerCase();
  const matched = doulaResponses.find((item) => item.keywords.some((keyword) => message.includes(keyword)));
  return matched ? matched.response : defaultResponse;
}
